// Generates supabase/seed.sql from src/data/seed.ts so the database and the app share one source of truth.
// Run: npx tsx scripts/gen-seed-sql.ts
import fs from 'node:fs';
import { GROUP_FIXTURES, PLAYERS, SEASON, TEAMS } from '../src/data/seed';

const data = {
  teams: TEAMS.map((t) => [t.id, t.name, t.short, t.logo, t.group]),
  players: PLAYERS.map((p) => [p.teamId, p.name, p.division, p.nameIncomplete]),
  fixtures: GROUP_FIXTURES.map((f) => [SEASON.weeks.findIndex((w) => w.date === f.date) + 1, f.group, f.home, f.away]),
};
const json = JSON.stringify(data).replace(/'/g, "''");
const sql = `-- Generated by scripts/gen-seed-sql.ts (Season 1). Safe to run once on an empty database.
do $$
declare d jsonb := '${json}'::jsonb; sid uuid; x jsonb; pid uuid;
begin
  if exists (select 1 from seasons where number = 1) then raise exception 'Season 1 already seeded'; end if;
  insert into seasons (name, number, status, starts_on, ends_on) values ('${SEASON.name}', 1, 'active', '${SEASON.weeks[0].date}', '${SEASON.weeks[5].date}') returning id into sid;
  insert into groups (season_id, name) values (sid, 'A'), (sid, 'B');
  for x in select * from jsonb_array_elements(d->'teams') loop
    insert into teams (season_id, slug, name, short, logo_path, group_id)
    select sid, x->>0, x->>1, x->>2, x->>3, g.id from groups g where g.season_id = sid and g.name = x->>4;
  end loop;
  for x in select * from jsonb_array_elements(d->'players') loop
    insert into persons (first_name, name_incomplete) values (x->>1, (x->>3)::boolean) returning id into pid;
    insert into season_players (season_id, person_id, team_id, division)
    select sid, pid, t.id, (x->>2)::division from teams t where t.season_id = sid and t.slug = x->>0;
  end loop;
  for x in select * from jsonb_array_elements(d->'fixtures') loop
    insert into fixtures (season_id, round, week, group_id, home_team, away_team)
    select sid, 'group', (x->>0)::int, g.id, h.id, a.id from groups g, teams h, teams a
    where g.season_id = sid and g.name = x->>1 and h.season_id = sid and h.slug = x->>2 and a.season_id = sid and a.slug = x->>3;
  end loop;
end $$;
`;
fs.writeFileSync('supabase/seed.sql', sql);
console.log('bytes:', sql.length);
